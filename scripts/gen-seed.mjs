// Generates supabase/seed.sql from supabase/seed-data.mjs.   npm run seed:gen
import { writeFileSync } from "node:fs";
import { companies, contacts, jobs, demo, demoProfile, demoApplications } from "../supabase/seed-data.mjs";

const q = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;
const json = (o) => `${q(JSON.stringify(o))}::jsonb`;
const hours = (h) => `now() - interval '${h} hours'`;
const days = (d) => `now() - interval '${d} days'`;

const sql = [];
sql.push("-- GENERATED by scripts/gen-seed.mjs from supabase/seed-data.mjs. Do not edit by hand.\n");

sql.push("insert into public.companies (slug, name, industry, size, hq, about) values");
sql.push(companies.map(([slug, name, industry, size, hq, about]) => `  (${q(slug)}, ${q(name)}, ${q(industry)}, ${q(size)}, ${q(hq)}, ${q(about)})`).join(",\n") + ";\n");

const dot = (n) => n.replace(/^(dr|prof)\.\s+/i, "").toLowerCase().replace(/[^a-z ]/g, "").trim().split(/\s+/);
const contactRows = contacts.flatMap(([co, fName, fTitle, rName, rTitle]) =>
  [["founder", fName, fTitle], ["recruiter", rName, rTitle]].map(([kind, name, title]) => {
    const p = dot(name);
    return `  ((select id from public.companies where slug = ${q(co)}), ${q(kind)}, ${q(name)}, ${q(title)}, ${q(`${p[0]}.${p[p.length - 1]}@${co}.example`)}, ${q(`https://${co}.example/team/${p.join("-")}`)})`;
  }),
);
sql.push("insert into public.company_contacts (company_id, kind, full_name, title, email, profile_url) values");
sql.push(contactRows.join(",\n") + ";\n");

sql.push("insert into public.jobs (slug, company_id, title, location, work_mode, job_type, level, salary_min, salary_max, currency, summary, responsibilities, requirements, skills, posted_at, closes_at) values");
sql.push(
  jobs
    .map(([slug, co, title, loc, mode, type, level, min, max, cur, skills, summary, resp, req, posted, closes]) =>
      `  (${q(slug)}, (select id from public.companies where slug = ${q(co)}), ${q(title)}, ${q(loc)}, ${q(mode)}, ${q(type)}, ${q(level)}, ${min}, ${max}, ${q(cur)}, ${q(summary)}, ${arr(resp)}, ${arr(req)}, ${arr(skills)}, ${hours(posted)}, now() + interval '${closes} days')`,
    )
    .join(",\n") + ";\n",
);

// Demo auth users (password is bcrypt-hashed by the database). Token columns must be '' not null for GoTrue.
for (const u of Object.values(demo)) {
  sql.push(`insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change, email_change_token_new)
values ('00000000-0000-0000-0000-000000000000', ${q(u.id)}, 'authenticated', 'authenticated', ${q(u.email)}, crypt(${q(u.password)}, gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}'::jsonb, ${json({ full_name: u.name })}, now(), now(), '', '', '', '');`);
  sql.push(`insert into auth.identities (id, user_id, identity_data, provider, provider_id, last_sign_in_at, created_at, updated_at)
values (gen_random_uuid(), ${q(u.id)}, ${json({ sub: u.id, email: u.email, email_verified: true })}, 'email', ${q(u.id)}, now(), now(), now());`);
}
sql.push(`update public.profiles set role = 'admin' where id = ${q(demo.admin.id)};`);
sql.push(`update public.profiles set headline = ${q(demoProfile.headline)}, phone = ${q(demoProfile.phone)}, location = ${q(demoProfile.location)}, summary = ${q(demoProfile.summary)}, skills = ${arr(demoProfile.skills)}, experience = ${json(demoProfile.experience)}, education = ${json(demoProfile.education)} where id = ${q(demo.candidate.id)};\n`);

// Applications: insert (the trigger writes the first 'applied' event), then replay the rest of the timeline.
for (const [slug, note, events] of demoApplications) {
  const first = events[0], last = events[events.length - 1];
  const where = `candidate_id = ${q(demo.candidate.id)} and job_id = (select id from public.jobs where slug = ${q(slug)})`;
  sql.push(`insert into public.applications (candidate_id, job_id, cover_note, status, created_at, updated_at)
values (${q(demo.candidate.id)}, (select id from public.jobs where slug = ${q(slug)}), ${q(note)}, 'applied', ${days(first[0])}, ${days(first[0])});`);
  for (const [d, status, evNote] of events.slice(1)) {
    sql.push(`insert into public.application_events (application_id, status, note, actor_id, created_at)
select id, ${q(status)}, ${q(evNote)}, ${q(demo.admin.id)}, ${days(d)} from public.applications where ${where};`);
  }
  sql.push(`update public.applications set status = ${q(last[1])}, updated_at = ${days(last[0])} where ${where};`);
}

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql.join("\n") + "\n");
console.log(`seed.sql: ${companies.length} companies, ${jobs.length} jobs, ${demoApplications.length} demo applications`);
